// Per-instance joining artefact (organism Step 1, door slice — joining half).
//
// Every Project Room instance auto-publishes, at zero host effort, two
// discovery documents that advertise the instance's OWN origin (the
// advertised origin of server/advertised-origin.mjs, derived per instance by
// PR #6191) and never the hosted service origin:
//
//   GET /.well-known/project-room-joining.json
//     A machine-readable joining file in the /.well-known/ shape. Its field
//     set — issuer, sign-in types, scopes, channels, revocation — is the
//     factual interface shape a joining agent needs, re-implemented
//     clean-room from the room's own joining contract (JOIN_TIERS, the MCP
//     identity mint, the agent-room create door). It is self-contained: an
//     agent starting from this file alone can complete the join walk in its
//     `join_steps` without reading any other document.
//
//   GET /.well-known/instance-agent-card.json
//     An A2A-style agent card (field conventions of A2A v1.0, Apache-2.0;
//     implemented from the format, no code copied) describing THIS instance,
//     signed as a JWS (RFC 7515, EdDSA) per A2A v1.0 §8.4 when a signing key
//     is configured for the instance. The signing utilities are the room's
//     own (server/agent-card-signing.mjs, signCardJws / verifyCardJws).
//
//   GET /.well-known/instance-jwks.json
//     The JWKS document for the instance card key, so a verifier can resolve
//     the JWS `kid`/`jku` exactly as with the hosted card.
//
// Signing-key posture — deliberately NOT auto-generated:
//   The hosted card's key is a pinned production key with a custody story
//   (server/agent-card-key.mjs). A self-hosted instance's card key is a
//   separate, per-instance decision: which key, generated by whom, stored
//   where, and how it rotates is the instance owner's act — for Project
//   Room's own instances it is John's key-custody decision, and this module
//   neither generates nor custodies a production key. A key is configured
//   only from the environment:
//     ROOM_JOINING_CARD_SIGNING_KEY       canonical base64 Ed25519 seed
//     ROOM_JOINING_CARD_SIGNING_KEY_FILE  path to a file holding that seed
//     ROOM_JOINING_CARD_KEY_ID            optional `kid` (default below)
//   With no key configured the card is still published, explicitly marked
//   signed:false with the reason — the same honesty rule the hosted card
//   follows (markUnsignedCard) — never silently unsigned, and the joining
//   file says the same in its `signing` block. A disposable proof instance
//   may point the _FILE variable at a throwaway key inside its own data
//   directory; that key dies with the instance and proves the mechanism,
//   not a production custody choice.
//
// Scope boundary: the hosted discovery documents (llms.txt, llms-full.txt,
// agent.json, the pinned-key agent-card.json, ard.json) are authored for the
// hosted origin and are owned by another slice; this module does not touch
// them. These three documents are additive and instance-scoped.
import { readFileSync } from "node:fs";
import { createPrivateKey, createPublicKey } from "node:crypto";
import { advertisedOrigin } from "./advertised-origin.mjs";
import { signCardJws, verifyCardJws, publicKeyToJwk, generateKeyPair } from "./agent-card-signing.mjs";
import { SOURCE_REVISION } from "./version.mjs";

export { generateKeyPair, verifyCardJws };

export const JOINING_PATH = "/.well-known/project-room-joining.json";
export const INSTANCE_AGENT_CARD_PATH = "/.well-known/instance-agent-card.json";
export const INSTANCE_JWKS_PATH = "/.well-known/instance-jwks.json";
export const JOINING_FORMAT = "project-room-joining/1";
export const DEFAULT_JOINING_KEY_ID = "project-room-instance-card-1";
export const UNSIGNED_JOINING_CARD_REASON =
  "no instance signing key configured (set ROOM_JOINING_CARD_SIGNING_KEY_FILE or ROOM_JOINING_CARD_SIGNING_KEY); key provisioning is the instance owner's decision";

const PKCS8_ED25519_PREFIX = Buffer.from("302e020100300506032b657004220420", "hex");

// Resolve the instance card signer from the environment. Returns
// { privateKey, publicKey, keyId } or null when no key is configured.
// Throws on a configured-but-invalid key: a host who asked for a signed
// card must fail loud at boot, not serve a card signed by garbage.
export function resolveJoiningSigner(env = process.env) {
  let seed = typeof env.ROOM_JOINING_CARD_SIGNING_KEY === "string" ? env.ROOM_JOINING_CARD_SIGNING_KEY.trim() : "";
  if (!seed && typeof env.ROOM_JOINING_CARD_SIGNING_KEY_FILE === "string" && env.ROOM_JOINING_CARD_SIGNING_KEY_FILE.trim()) {
    seed = readFileSync(env.ROOM_JOINING_CARD_SIGNING_KEY_FILE.trim(), "utf8").trim();
  }
  if (!seed) return null;
  const keyId = typeof env.ROOM_JOINING_CARD_KEY_ID === "string" && env.ROOM_JOINING_CARD_KEY_ID.trim()
    ? env.ROOM_JOINING_CARD_KEY_ID.trim() : DEFAULT_JOINING_KEY_ID;
  const raw = Buffer.from(seed, "base64");
  if (raw.length !== 32 || raw.toString("base64") !== seed) {
    throw new Error("ROOM_JOINING_CARD_SIGNING_KEY(_FILE) must hold the canonical base64 of a 32-byte Ed25519 seed");
  }
  const privateKeyObject = createPrivateKey({ key: Buffer.concat([PKCS8_ED25519_PREFIX, raw]), format: "der", type: "pkcs8" });
  const publicKey = Buffer.from(createPublicKey(privateKeyObject).export({ format: "jwk" }).x, "base64url").toString("base64");
  return { privateKey: seed, publicKey, keyId };
}

