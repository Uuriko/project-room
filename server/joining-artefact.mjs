// The join walk, self-contained. A scripted agent following only these
// steps — MCP initialize, identity mint, room create, membership verify —
// reaches a joined, identity-holding state on this instance.
function joinSteps(origin) {
  return [
    { step: 1, action: "mcp_initialize", channel: "mcp", method: "POST", url: `${origin}/mcp`,
      body: { jsonrpc: "2.0", id: 1, method: "initialize", params: { protocolVersion: "2025-11-25", capabilities: {}, clientInfo: { name: "joining-agent", version: "1" } } },
      expect: "a JSON-RPC result naming this server; no credential is needed for the public discovery catalog" },
    { step: 2, action: "identity_mint", channel: "mcp", method: "POST", url: `${origin}/mcp`,
      body: { jsonrpc: "2.0", id: 2, method: "tools/call", params: { name: "room_identity_mint", arguments: { displayName: "Your agent name" } } },
      save: ["structuredContent.identityId", "structuredContent.secret", "structuredContent.privateKey"],
      expect: "the one-time identity secret and Ed25519 private key ride in structuredContent only and are shown once — save them privately before continuing; if the answer is proof_required, solve its proof recipe and resend the same call with proof set" },
    { step: 3, action: "room_create", channel: "http", method: "POST", url: `${origin}/api/agent-rooms`,
      headers: { Authorization: "Bearer <saved-identity-secret>", "Content-Type": "application/json" },
      body: { title: "Your room title", purpose: "What this room is for" },
      save: ["roomId"],
      expect: "201 with the created room; the creating identity owns it and is its member. To enter an existing room instead, use the invite-redeem or access-request sign-in types above" },
    { step: 4, action: "verify_membership", channel: "http", method: "GET", url: `${origin}/api/rooms/{roomId}/activation-pack`,
      headers: { Authorization: "Bearer <saved-identity-secret>" },
      expect: "200: an authenticated read of the room you created — this is the joined, identity-holding state. Membership does not mean your host is continuously listening" },
  ];
}

export function joiningDocument({ origin, signer = null } = {}) {
  const own = advertisedOrigin(origin);
  return {
    format: JOINING_FORMAT,
    issuer: own,
    instance: {
      name: "Project Room (instance)",
      origin: own,
      software: "project-room",
      revision: SOURCE_REVISION === "unstamped" ? "dev" : SOURCE_REVISION,
      description: "A Project Room instance: humans direct, agents execute, work is reviewed and receipted. This document is published automatically by the instance itself and names only this instance's origin.",
    },
    sign_in_types: signInTypes(own),
    scopes: {
      invite_profiles: ["chat", "contribute", "review", "collaborate"],
      note: "Joining grants basic read/chat only. Work permissions (claiming, reviewing, settling) are separate per-room grants named by the invite profile or by the room owner; a member holding none of them is refused work writes by design.",
    },
    channels: {
      mcp: { url: `${own}/mcp`, protocolVersion: "2025-11-25", note: "Public discovery catalog without a credential; the saved identity secret as bearer on the same URL unlocks the enrolled room profile." },
      http: { url: own, note: "JSON APIs under /api/… on this origin; send the identity secret as Authorization: Bearer <secret>. Never forward credentials to another origin." },
      a2a: { url: `${own}/a2a`, note: "A2A JSON-RPC door: message/send answers with how to join. It holds no credentials and reads no room data." },
    },
    revocation: {
      summary: "Every joining path is revocable by the party who granted it: a room owner can disconnect a guest or a member and revoke their room credentials; an invite is single-use and expires; a guest pass is short-lived and owner-revocable; an enrolled key is owner-revocable. Revoking a member revokes that member's room credentials.",
      guest_pass: "owner disconnects the guest or revokes all guests of the room",
      invite: "single-use; expires between 5 minutes and 30 days (default 24h)",
      identity: "an identity secret is shown once and never re-issued by a read path; a lost secret is not recoverable from the instance",
    },
    agent_card: `${own}${INSTANCE_AGENT_CARD_PATH}`,
    jwks: `${own}${INSTANCE_JWKS_PATH}`,
    signing: signer
      ? { status: "signed", alg: "EdDSA", keyId: signer.keyId, jwks: `${own}${INSTANCE_JWKS_PATH}`,
          note: "The instance agent card carries an A2A v1.0 JWS signature (RFC 7515) verifiable against the JWKS document above." }
      : { status: "unsigned", alg: "EdDSA", reason: UNSIGNED_JOINING_CARD_REASON,
          note: "The joining file itself is unsigned; the instance agent card is published explicitly marked signed:false until the instance owner provisions a signing key." },
    join_steps: joinSteps(own),
  };
}

// A2A-style agent card for THIS instance. Field conventions follow A2A
// v1.0 (supportedInterfaces, skills, securitySchemes, capabilities,
// signatures); every URL is this instance's own origin.
export function instanceAgentCard({ origin, signer = null } = {}) {
  const own = advertisedOrigin(origin);
  const card = {
    name: "Project Room (instance)",
    description: "Project Room connects existing AI agents so people and agents can share context, hand off work and keep results across sessions. This card describes one self-hosted instance and names only that instance's origin. Join from the joining file at /.well-known/project-room-joining.json on this origin: mint an identity over MCP, then create or enter a room. Discovery only in this card; room actions stay on MCP and the HTTP APIs of this origin.",
    version: "1",
    protocolVersion: "1.0",
    url: own,
    preferredTransport: "HTTP+JSON",
    supportedInterfaces: [
      { url: own, protocolBinding: "HTTP+JSON", protocolVersion: "1.0" },
      { url: `${own}/mcp`, protocolBinding: "MCP", protocolVersion: "2025-11-25" },
      { url: `${own}/a2a`, protocolBinding: "JSONRPC", protocolVersion: "1.0" },
    ],
    defaultInputModes: ["text/plain"],
    defaultOutputModes: ["text/plain"],
    capabilities: { streaming: false, pushNotifications: false },
    skills: [
      { id: "join-instance", name: "Join this instance",
        description: `Mint an identity (MCP room_identity_mint or POST ${own}/api/agent-identities), then create a room you own (POST ${own}/api/agent-rooms) or enter one by invite or access request. The joining file at ${own}${JOINING_PATH} carries the full step-by-step walk.`,
        tags: ["room", "join", "connect"], examples: ["Join this Project Room instance"],
        inputModes: ["text/plain"], outputModes: ["text/plain"] },
      { id: "identity-mint", name: "Identity create",
        description: "Mint identity with only this origin: MCP room_identity_mint, or POST /api/agent-identities. One-time pri_… secret plus an Ed25519 keypair; the private key is shown once. Save both privately.",
        tags: ["room", "join", "identity"], examples: ["identity-create"],
        inputModes: ["text/plain"], outputModes: ["text/plain"] },
      { id: "agent-room-create", name: "Agent-owned room",
        description: "Mint identity → create a room it owns (POST /api/agent-rooms) → mint a peer invite at POST /api/rooms/{roomId}/agent-invites with {\"profile\":\"chat|contribute|review|collaborate\"}. No human owner token.",
        tags: ["room", "join", "ownership"], examples: ["room-create", "invite-code"],
        inputModes: ["text/plain"], outputModes: ["text/plain"] },
    ],
    securitySchemes: {
      bearerAuth: { type: "http", scheme: "bearer", description: "Every credential travels in the Authorization header as a token — the agent identity secret (pri_…), a guest pass, or an owner-issued enrolled agent API key (rak_…)." },
      guestLinkAuth: { type: "apiKey", in: "header", name: "Authorization", description: "Single-use GX- invite code redeemed with an Ed25519-signed agent card; yields a short-lived guest pass." },
    },
    securityRequirements: [{ bearerAuth: [] }, { guestLinkAuth: [] }],
    provider: { organization: "Project Room instance", url: own },
    endpoints: {
      joining: `${own}${JOINING_PATH}`,
      agent_card: `${own}${INSTANCE_AGENT_CARD_PATH}`,
      jwks: `${own}${INSTANCE_JWKS_PATH}`,
      mcp: `${own}/mcp`,
      identity_mint: `${own}/api/agent-identities`,
      room_create: `${own}/api/agent-rooms`,
      invite_redeem: `${own}/api/agent-invites/redeem`,
      access_requests: `${own}/api/access-requests`,
    },
  };
  if (signer) {
    // keyId is part of the served card, so it must be set before signing:
    // the JWS payload is the served card minus `signatures` (the same rule
    // verifyCardJws applies), envelope fields included.
    card.keyId = signer.keyId;
    card.signatures = [signCardJws({ card, privateKey: signer.privateKey, keyId: signer.keyId, jku: `${own}${INSTANCE_JWKS_PATH}` })];
  } else {
    card.signed = false;
    card.unsignedReason = UNSIGNED_JOINING_CARD_REASON;
  }
  return card;
}

export function instanceJwks({ signer = null } = {}) {
  if (!signer) return { keys: [] };
  return { keys: [publicKeyToJwk({ publicKey: signer.publicKey, keyId: signer.keyId })] };
}

export function joiningDocumentJson(options) { return JSON.stringify(joiningDocument(options), null, 2) + "\n"; }
export function instanceAgentCardJson(options) { return JSON.stringify(instanceAgentCard(options), null, 2) + "\n"; }
export function instanceJwksJson(options) { return JSON.stringify(instanceJwks(options), null, 2) + "\n"; }

// Route-table rows (batch RT shape, mirroring WORK_RECEIPT_EXTENSION_ROUTES).
// The handler reads the origin from the request context — the same
// expectedOrigin() the invite URLs use — and the signer resolved once from
// the process environment, so every instance serves its own documents.
let cachedSigner; // undefined = unresolved, null = none configured
function routeSigner() {
  // A configured-but-invalid key throws here and fails the request loud,
  // rather than silently serving an unsigned card the host believes signed.
  if (cachedSigner === undefined) cachedSigner = resolveJoiningSigner(process.env);
  return cachedSigner;
}

function joiningRouteHandler(kind) {
  return ctx => {
    const origin = typeof ctx.expectedOrigin === "function" ? ctx.expectedOrigin() : undefined;
    const signer = routeSigner();
    const body = kind === "joining" ? joiningDocumentJson({ origin, signer })
      : kind === "card" ? instanceAgentCardJson({ origin, signer })
      : instanceJwksJson({ signer });
    const bytes = new TextEncoder().encode(body);
    ctx.res.setHeader("X-Robots-Tag", "all");
    ctx.res.writeHead(200, { "Content-Type": "application/json; charset=utf-8", "Content-Length": bytes.byteLength });
    return ctx.res.end(ctx.req.method === "HEAD" ? undefined : bytes);
  };
}

const JOINING_ROUTE_DEFS = Object.freeze([
  Object.freeze({ id: "project-room-joining", path: JOINING_PATH, kind: "joining",
    parity: "exempt:static public joining document; the join itself runs over MCP and HTTP doors named inside it",
    publication: "open:static joining document generated from this instance's own origin; no room or member data" }),
  Object.freeze({ id: "instance-agent-card", path: INSTANCE_AGENT_CARD_PATH, kind: "card",
    parity: "exempt:static public A2A-style instance card; no MCP operation",
    publication: "open:static instance agent card generated from this instance's own origin; no room or member data" }),
  Object.freeze({ id: "instance-jwks", path: INSTANCE_JWKS_PATH, kind: "jwks",
    parity: "exempt:static public JWKS key-discovery document; no MCP operation",
    publication: "open:static JWKS document carrying only the instance card public key; no room or member data" }),
]);

export const JOINING_ROUTES = Object.freeze(JOINING_ROUTE_DEFS.flatMap(def =>
  ["GET", "HEAD"].map(method => Object.freeze({
    id: `${def.id}-${method.toLowerCase()}`, method, path: def.path,
    auth: "none", capability: null, scope: "public", handler: joiningRouteHandler(def.kind),
    parity: def.parity, publication: def.publication,
    schema: { response: { type: "object" } }, events: [],
  }))));
