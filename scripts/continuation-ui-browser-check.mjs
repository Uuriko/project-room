import test from 'node:test';
import assert from 'node:assert/strict';
import { rmSync } from 'node:fs';
import { chromium } from 'playwright';
import { createAcceptanceFixture } from './acceptance-fixture.mjs';
import { createRoomServer } from '../server/http.mjs';
import { EVENT_TYPES as T } from '../src/events.js';
import { signInFixture } from './auth-signin.mjs';
import { clickChrome, openSearch } from './room-chrome.mjs';

test('continuation uses the selected authenticated work and requires refresh when it changes', { timeout: 60000 }, async t => {
  const f = createAcceptanceFixture(), server = createRoomServer({ store: f.store, streamInterval: 40 });
  let browser;
  t.after(async () => {
    await browser?.close(); server.closeStreams(); server.closeAllConnections();
    if (server.listening) await new Promise(resolve => server.close(resolve));
    f.store.close(); rmSync(f.directory, { recursive: true, force: true });
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  browser = await chromium.launch({ headless: true, ...(process.env.ROOM_TEST_CHROMIUM_PATH ? { executablePath: process.env.ROOM_TEST_CHROMIUM_PATH } : {}) });
  const page = await browser.newPage({ serviceWorkers: 'block' }); const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`); await signInFixture(page, f.keys.owner);
  await openSearch(page); await page.locator('#message-search').fill('Test: prepare an agenda');
  await page.locator('#search-list [data-open-work="test-handoff"]').click();
  const card = page.locator('[data-work-record-id="test-handoff"]');
  await card.locator('.work-details > summary').click();
  await card.getByRole('button', { name: 'Continue with an agent', exact: true }).click();
  await page.locator('#continuation-copy:enabled').waitFor();
  const first = await page.locator('#continuation-preview').inputValue();
  assert.match(first, /# Work continuation/); assert.match(first, /Test: prepare an agenda/);
  assert.doesNotMatch(first, /viewerSessionBinding|accountAccessKey|Please prepare an agenda/);
  f.store.command(f.keys.producer, 'commons', { id: crypto.randomUUID(), type: T.WORK_ACCEPTED, data: { workItemId: 'test-handoff', expectedRevision: 0 } });
  await page.getByText('Work changed. Refresh before copying.', { exact: true }).waitFor();
  assert.equal(await page.locator('#continuation-copy').isDisabled(), true);
  await page.locator('#continuation-refresh').click();
  await page.locator('#continuation-copy:enabled').waitFor();
  assert.match(await page.locator('#continuation-preview').inputValue(), /"workRevision": 1/);
  await page.evaluate(() => { navigator.clipboard.writeText = () => new Promise(resolve => { window.finishContinuationCopy = resolve; }); });
  await page.locator('#continuation-copy').click();
  f.store.command(f.keys.producer, 'commons', { id: crypto.randomUUID(), type: T.WORK_STARTED, data: { workItemId: 'test-handoff', expectedRevision: 1 } });
  await page.getByText('Work changed. Refresh before copying.', { exact: true }).waitFor();
  await page.evaluate(() => window.finishContinuationCopy());
  await page.getByText('Work changed during copy. Refresh and copy again.', { exact: true }).waitFor();
  assert.equal(await page.locator('#continuation-copy').isDisabled(), true);
  await page.locator('#continuation-close').click();
  let releaseRead, receivedRead, finishedRead;
  const readStarted = new Promise(resolve => { receivedRead = resolve; });
  const readFinished = new Promise(resolve => { finishedRead = resolve; });
  const heldRead = new Promise(resolve => { releaseRead = resolve; });
  await page.route('**/work-context?*', async route => { const response = await route.fetch(); receivedRead(); await heldRead; await route.fulfill({ response }); finishedRead(); });
  await card.getByRole('button', { name: 'Continue with an agent', exact: true }).click();
  await readStarted; await page.locator('#continuation-close').click();
  await page.locator('#session-menu-button').click(); await clickChrome(page, '#signout-button');
  await page.locator('#auth-panel').waitFor({ state: 'visible' }); releaseRead(); await readFinished;
  await page.waitForFunction(() => !document.getElementById('continuation-dialog').open);
  assert.equal(await page.locator('#continuation-preview').inputValue(), '', 'closed session never restores the held private read');
  assert.deepEqual(errors, []);
});
