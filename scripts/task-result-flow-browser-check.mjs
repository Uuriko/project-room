// Synthetic browser usability checks; these are not participant research.
import test from 'node:test';
import assert from 'node:assert/strict';
import { rmSync } from 'node:fs';
import { chromium } from 'playwright';
import { createResultsFixture } from './results-fixture.mjs';
import { createRoomServer } from '../server/http.mjs';
import { EVENT_TYPES as T } from '../src/events.js';
import { fillAccessKey } from './auth-signin.mjs';

for (const mobile of [false, true]) test(`task to result ${mobile ? 'mobile' : 'desktop'}: direct artifact and recoverable progress`, { timeout: 60000 }, async t => {
  const f = createResultsFixture(), server = createRoomServer({ store: f.store, streamInterval: 40 });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); server.closeStreams(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); f.store.close(); rmSync(f.directory, { recursive: true, force: true }); });
  const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`); await fillAccessKey(page, f.keys.owner);
  await page.getByRole('button', { name: 'Enter room', exact: true }).click();
  const result = page.locator('[data-work-record-id="approved-result"]');
  await result.waitFor();
  assert.equal(await result.locator('.work-details').evaluate(el => el.open), false);
  assert.equal(await result.getByRole('link', { name: 'Open result ↗', exact: true }).isVisible(), true);
  assert.equal(await result.getByRole('link', { name: 'Open result ↗', exact: true }).getAttribute('href'), 'https://example.invalid/fictional-result');
  f.send('owner', T.WORK_PROPOSED, { workItemId: 'recover', title: 'Recover a report', definitionOfDone: 'A concise report.', accountableMemberId: 'owner', mode: 'read', independentVerificationRequired: false, ownerDecisionRequired: false });
  const revision = () => f.store.room('commons').state.workItems.recover.revision;
  f.send('owner', T.SESSION_STARTED, { workItemId: 'recover', expectedRevision: revision() });
  f.send('owner', T.SESSION_STOPPED, { workItemId: 'recover', expectedRevision: revision(), status: 'failed', outputs: ['log:first-attempt'] });
  const card = page.locator('[data-work-record-id="recover"]');
  await card.locator('.work-recovery').waitFor();
  const before = revision();
  await card.getByRole('button', { name: 'Continue with saved context' }).click();
  assert.equal(await page.locator('#portable-progress').isChecked(), true);
  assert.match(await page.locator('#packet-preview').inputValue(), /Run interrupted/);
  assert.match(await page.locator('#packet-preview').inputValue(), /concise report/);
  await page.locator('#portable-close').click();
  assert.equal(revision(), before, 'viewing recovery never starts a second worker');
  await card.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `/tmp/project-room-task-result-${mobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  f.send('owner', T.SESSION_STARTED, { workItemId: 'recover', expectedRevision: revision() });
  await card.locator('.work-recovery').waitFor({ state: 'detached' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  assert.deepEqual(errors, []);
});
