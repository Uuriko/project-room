// Build-time signer for the room's A2A Agent Card (RC-2026-09-23-105).
//
// Runs after scripts/stamp-version.mjs so agentCard() sees the stamped
// revision. Signs the canonical card bytes with the room's dedicated Ed25519
// key (server/agent-card-signing.mjs, the same house standard the agent
// directory uses) and writes deploy/agent-card-signed.mjs, which
// deploy/agent-discovery.mjs only honors when the signature covers exactly
// the served build's revision.
//
// The private key is read from ROOM_AGENT_CARD_SIGNING_KEY (canonical base64
// seed) or ~/.config/project-room/agent-card-signing.key. It is never
// committed, never logged, never transmitted. Missing keys stop the build.
// Local unsigned builds require the explicit --allow-unsigned argument.
// Custody, rotation, recovery: docs/AGENT-CARD-CUSTODY.md.
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { agentCard } from "../deploy/agent-discovery.mjs";
import { AGENT_CARD_AGENT_ID, AGENT_CARD_PUBLIC_KEY } from "../deploy/agent-card-key.mjs";
import { isValidPublicKey, signCard, verifyCardSignature } from "../server/agent-card-signing.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "deploy", "agent-card-signed.mjs");
const KEY_FILE = join(homedir(), ".config", "project-room", "agent-card-signing.key");

const loadPrivateKey = () => {
  const fromEnv = (process.env.ROOM_AGENT_CARD_SIGNING_KEY || "").trim();
  if (fromEnv) return fromEnv;
  try {
    return readFileSync(KEY_FILE, "utf8").trim();
  } catch {
    return null;
  }
};

const nullModule = (why) => `// Generated by scripts/sign-agent-card.mjs — do not hand-edit.
// ${why}
export const AGENT_CARD_SIGNATURE = null;
export const AGENT_CARD_SIGNED_REVISION = null;
`;

export function signAgentCard({ privateKey, card, publicKey = AGENT_CARD_PUBLIC_KEY,
  agentId = AGENT_CARD_AGENT_ID, outputPath = OUT, allowUnsigned = false }) {
  if (!privateKey) {
    if (!allowUnsigned) throw new Error("sign-agent-card: signing key unavailable; release stopped. Restore signing custody before deployment.");
    writeFileSync(outputPath, nullModule("Unsigned: no private key at ROOM_AGENT_CARD_SIGNING_KEY or ~/.config/project-room/agent-card-signing.key."));
    console.log("sign-agent-card: no private key; card will be served unsigned.");
    return;
  }
  if (!isValidPublicKey(publicKey)) {
    throw new Error("sign-agent-card: pinned public key in deploy/agent-card-key.mjs is not a valid Ed25519 key");
  }
  const revision = card?.deployed?.revision;
  if (typeof revision !== "string" || revision.length === 0) {
    throw new Error("sign-agent-card: card has no deployed.revision to bind the signature to");
  }
  const signature = signCard({ agentId, card, privateKey });
  // Fail closed: the signature must verify against the PINNED public key, so
  // a wrong private key can never ship a card that claims this key id.
  const ok = verifyCardSignature({
    agentId,
    card,
    publicKey,
    signature,
  });
  if (!ok) {
    throw new Error("sign-agent-card: fresh signature does not verify against the pinned public key; refusing to write");
  }
  writeFileSync(outputPath, `// Generated by scripts/sign-agent-card.mjs — do not hand-edit.
// Signed ${new Date().toISOString()} for revision ${revision}.
export const AGENT_CARD_SIGNATURE = ${JSON.stringify(signature)};
export const AGENT_CARD_SIGNED_REVISION = ${JSON.stringify(revision)};
`);
  console.log(`sign-agent-card: signed card for revision ${revision}.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const args = process.argv.slice(2);
    if (args.some(arg => arg !== "--allow-unsigned")) throw new Error("Unknown signing option");
    signAgentCard({ privateKey: loadPrivateKey(), card: agentCard(), allowUnsigned: args.includes("--allow-unsigned") });
  } catch {
    console.error("sign-agent-card: signing failed; release stopped. Check the private key and pinned public key. No unsigned fallback was written.");
    process.exitCode = 1;
  }
}
