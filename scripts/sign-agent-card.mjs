// Build-time signer for the room's A2A Agent Card (RC-2026-09-23-105).
//
// Runs after scripts/stamp-version.mjs so agentCard() sees the stamped
// revision. Signs the canonical card bytes with the room's dedicated Ed25519
// key (server/agent-card-signing.mjs, the same house standard the agent
// directory uses), then signs the card-plus-envelope as an A2A v1.0 §8.4 JWS
// (RC-2026-09-27-2715), and writes deploy/agent-card-signed.mjs, which
// deploy/agent-discovery.mjs only honors when the signature covers exactly
// the served build's revision.
//
// The private key is read from ROOM_AGENT_CARD_SIGNING_KEY (canonical base64
// seed) or ~/.config/project-room/agent-card-signing.key. It is never
// committed, never logged, never transmitted. Missing keys stop the build.
// Local unsigned builds require the explicit --allow-unsigned argument. A key
// that loads but fails pinned-key verification (wrong key on file) also stops
// the build unless --allow-unsigned is passed — then the card ships unsigned
// with a loud warning instead of failing the release.
// Custody, rotation, recovery: docs/AGENT-CARD-CUSTODY.md.
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { agentCard, attachCardSignatureEnvelope, AGENT_CARD_JWKS_URL } from "../deploy/agent-discovery.mjs";
import { AGENT_CARD_AGENT_ID, AGENT_CARD_PUBLIC_KEY, AGENT_CARD_KEY_ID } from "../deploy/agent-card-key.mjs";
import { isValidPublicKey, signCard, verifyCardSignature, signCardJws, verifyCardJws } from "../server/agent-card-signing.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "deploy", "agent-card-signed.mjs");
const KEY_FILE = join(homedir(), ".config", "project-room", "agent-card-signing.key");

const loadPrivateKey = () => {
  const fromEnv = (process.env.ROOM_AGENT_CARD_SIGNING_KEY || "").trim();
  if (fromEnv) return fromEnv;
  try {
    return readFileSync(KEY_FILE, "utf8").trim();
  } catch {
    return null;
  }
};

const nullModule = (why) => `// Generated by scripts/sign-agent-card.mjs — do not hand-edit.
// ${why}
// AGENT_CARD_UNSIGNED_REASON records the explicit unsigned opt-in (never
// null here): the boot gate (server/boot-config.mjs) treats a null reason as
// an unrecorded, silent unsigned default and fails loud.
export const AGENT_CARD_SIGNATURE = null;
export const AGENT_CARD_SIGNED_REVISION = null;
export const AGENT_CARD_UNSIGNED_REASON = ${JSON.stringify(why)};
export const AGENT_CARD_JWS_SIGNATURES = null;
`;

export function signAgentCard({ privateKey, card, publicKey = AGENT_CARD_PUBLIC_KEY,
  agentId = AGENT_CARD_AGENT_ID, outputPath = OUT, allowUnsigned = false }) {
  if (!privateKey) {
    if (!allowUnsigned) throw new Error("sign-agent-card: signing key unavailable; release stopped. Restore signing custody before deployment.");
    writeFileSync(outputPath, nullModule("Unsigned: explicit --allow-unsigned was passed and no private key was found at ROOM_AGENT_CARD_SIGNING_KEY or ~/.config/project-room/agent-card-signing.key; the card carries no signature."));
    console.log("sign-agent-card: no private key; card will be served unsigned.");
    return;
  }
  if (!isValidPublicKey(publicKey)) {
    throw new Error("sign-agent-card: pinned public key in deploy/agent-card-key.mjs is not a valid Ed25519 key");
  }
  const revision = card?.deployed?.revision;
  if (typeof revision !== "string" || revision.length === 0) {
    throw new Error("sign-agent-card: card has no deployed.revision to bind the signature to");
  }
  const signature = signCard({ agentId, card, privateKey });
  // Fail closed: the signature must verify against the PINNED public key, so
  // a wrong private key can never ship a card that claims this key id.
  const ok = verifyCardSignature({
    agentId,
    card,
    publicKey,
    signature,
  });
  if (!ok) {
    if (!allowUnsigned) {
      throw new Error("sign-agent-card: fresh signature does not verify against the pinned public key; refusing to write");
    }
    writeFileSync(outputPath, nullModule("Unsigned: explicit --allow-unsigned was passed and the on-file private key does not match the pinned public key; the card carries no signature."));
    console.warn("sign-agent-card: WARNING: private key does not match the pinned public key; card will be served UNSIGNED. Restore signing custody before the next release.");
    return;
  }
  // A2A v1.0 §8.4 JWS (RC-2026-09-27-2715): sign the card PLUS the legacy
  // envelope above — the JWS payload excludes only `signatures`, so the
  // envelope must be attached first. attachCardSignatureEnvelope() is the
  // same builder agentCard() uses at serve time, so the signed bytes are
  // byte-identical to what verifiers recompute from the served card.
  const cardWithEnvelope = attachCardSignatureEnvelope({ ...card }, {
    signature,
    jwsSignatures: null,
    revision,
  });
  const jws = signCardJws({ card: cardWithEnvelope, privateKey, keyId: AGENT_CARD_KEY_ID, jku: AGENT_CARD_JWKS_URL });
  // Fail closed on the JWS too: it must verify against the PINNED public key.
  if (!verifyCardJws({ card: cardWithEnvelope, publicKey, jws })) {
    if (!allowUnsigned) {
      throw new Error("sign-agent-card: fresh JWS does not verify against the pinned public key; refusing to write");
    }
    writeFileSync(outputPath, nullModule("Unsigned: explicit --allow-unsigned was passed and the freshly computed JWS does not verify against the pinned public key; the card carries no signature."));
    console.warn("sign-agent-card: WARNING: fresh JWS does not verify against the pinned public key; card will be served UNSIGNED. Restore signing custody before the next release.");
    return;
  }
  writeFileSync(outputPath, `// Generated by scripts/sign-agent-card.mjs — do not hand-edit.
// Signed ${new Date().toISOString()} for revision ${revision}.
export const AGENT_CARD_SIGNATURE = ${JSON.stringify(signature)};
export const AGENT_CARD_SIGNED_REVISION = ${JSON.stringify(revision)};
// Signed build: the unsigned opt-in is explicitly not recorded.
export const AGENT_CARD_UNSIGNED_REASON = null;
export const AGENT_CARD_JWS_SIGNATURES = ${JSON.stringify([jws])};
`);
  console.log(`sign-agent-card: signed card for revision ${revision} (house envelope + A2A v1.0 JWS).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const args = process.argv.slice(2);
    if (args.some(arg => arg !== "--allow-unsigned")) throw new Error("Unknown signing option");
    signAgentCard({ privateKey: loadPrivateKey(), card: agentCard(), allowUnsigned: args.includes("--allow-unsigned") });
  } catch {
    console.error("sign-agent-card: signing failed; release stopped. Check the private key and pinned public key. No unsigned fallback was written.");
    process.exitCode = 1;
  }
}
