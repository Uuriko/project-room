import test from 'node:test';
import assert from 'node:assert/strict';
import { rmSync } from 'node:fs';
import { chromium } from 'playwright';
import twilio from 'twilio';
import { createAcceptanceFixture } from './acceptance-fixture.mjs';
import { createRoomServer } from '../server/http.mjs';
import { importTwilioMessage } from '../server/twilio-inbox-import.mjs';
import { prepareInboxResult } from './inbox-result-fixture.mjs';

for (const provider of ['sms','whatsapp']) test(`${provider} signed text renders privately in Inbox`, async t => {
  const f=createAcceptanceFixture(), account=f.store.accountForMember('commons','owner');
  const key=f.store.issueAccountAccessKey(account.id),slot=f.store.createAccountSessionSlot();
  const session=f.store.loginAccountSession(slot.token,key,0),prefix=provider==='sms'?'':'whatsapp:';
  const c={active:true,accountId:account.id,connectionId:'twilio-test',authEpoch:0,revision:1,accountSid:'AC'+'a'.repeat(32),
    authToken:'test-secret',webhookUrl:'https://example.test/incoming',addresses:[prefix+'+14155550100']};
  const p={AccountSid:c.accountSid,MessageSid:'SM'+'b'.repeat(32),From:prefix+'+14155550101',To:c.addresses[0],NumMedia:'0',Body:'Private signed message fixture'};
  importTwilioMessage({store:f.store,slot,session,withConnection:fn=>fn(c),request:{rawBody:new URLSearchParams(p).toString(),
    contentType:'application/x-www-form-urlencoded',signature:twilio.getExpectedTwilioSignature(c.authToken,c.webhookUrl,p)}});
  let connectionState='active',connectionRevision=1;const disconnects=[];
  const twilioConnections={list:()=>[{connectionId:'twilio-test',provider,state:connectionState,revision:connectionRevision}],
    disconnect:(_session,connectionId,expectedRevision)=>{disconnects.push({connectionId,expectedRevision});connectionState='disconnected';connectionRevision++;
      return {connectionId,state:connectionState,revision:connectionRevision};}};
  const server=createRoomServer({store:f.store,twilioConnections});await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch({headless:true});
  t.after(async()=>{await browser.close();server.closeStreams();server.closeAllConnections();await new Promise(r=>server.close(r));f.store.close();rmSync(f.directory,{recursive:true,force:true});});
  const page=await browser.newPage({viewport:{width:390,height:844}});page.setDefaultTimeout(7000);
  await page.goto(`http://127.0.0.1:${server.address().port}/?room=commons`);
  await page.locator('#sign-in-entry').click();await page.locator('#access-key').fill(key);await page.locator('#auth-form button[type=submit]').click();
  await page.locator('#main').waitFor({state:'visible'});await page.locator('#nav-inbox').click();
  await page.getByRole('heading',{name:provider==='sms'?'SMS message':'WhatsApp message',exact:true}).waitFor();
  await page.getByText('Private signed message fixture',{exact:true}).waitFor();
  assert.equal(await page.locator('#inbox-source-label').textContent(),`${provider==='sms'?'SMS':'WhatsApp'} · only you`);
  assert.equal(await page.locator('#inbox-ask').isVisible(),true);
  const beforePrivate=f.store.room('commons').sequence;
  await page.locator('#inbox-ask').click();await page.locator('#inbox-excerpt-text').waitFor();
  await page.locator('#inbox-share-scope').selectOption('private');
  await page.locator('#inbox-excerpt-text').evaluate(el=>{el.setSelectionRange(0,14);el.dispatchEvent(new Event('select'));});
  assert.equal(await page.locator('#inbox-share-confirm').isDisabled(),true);
  await page.locator('#inbox-share-member-list input[value="producer"]').check();
  await page.locator('#inbox-share-confirm').click();await page.locator('#inbox-share-dialog').waitFor({state:'hidden'});
  await page.locator('#inbox-grant-list').getByRole('button',{name:'Revoke',exact:true}).waitFor();
  const sourceId=f.store.inbox.list(slot.token,session.sessionBinding).sources[0].id;
  const grant=f.store.inbox.grants(slot.token,sourceId,session.sessionBinding).grants[0];
  assert.equal(f.store.room('commons').sequence,beforePrivate);
  assert.equal(f.store.inbox.readGrant(f.keys.producer,'commons',grant.grantId).body,'Shared message excerpt\n\nPrivate signed');
  assert.throws(()=>f.store.inbox.readGrant(f.keys.reviewer,'commons',grant.grantId),{status:404});
  await page.locator('#inbox-grant-list').getByRole('button',{name:'Revoke',exact:true}).click();
  await page.locator('#inbox-grant-list').getByText('1 recipient · Revoked',{exact:false}).waitFor();
  assert.throws(()=>f.store.inbox.readGrant(f.keys.producer,'commons',grant.grantId),{status:404});
  await page.locator('#inbox-ask').click();await page.locator('#inbox-excerpt-text').waitFor();
  await page.locator('#inbox-excerpt-text').evaluate(el=>{el.setSelectionRange(0,14);el.dispatchEvent(new Event('select'));});
  const sharedResponse=page.waitForResponse(r=>r.url().endsWith('/api/inbox/commands')&&r.request().postDataJSON()?.action==='source.excerpt');
  await page.locator('#inbox-share-confirm').click();await page.locator('#inbox-share-dialog').waitFor({state:'hidden'});
  assert.equal(f.store.room('commons').state.messages.at(-1).body,'Shared message excerpt\n\nPrivate signed');
  const shared=await(await sharedResponse).json();
  const result=prepareInboxResult(f,slot.token,session.sessionBinding,{sourceId,shareReceipt:shared});
  await page.locator('#nav-inbox').click();await page.locator('#inbox-source-body').getByText('Private signed message fixture',{exact:true}).waitFor();
  await page.locator('#inbox-result-list').getByRole('button',{name:'Use result',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#inbox-result-use').disabled);
  assert.equal(await page.locator('#inbox-result-body').textContent(),result.body);
  await page.locator('#inbox-result-use').click();
  await page.waitForFunction(body=>document.querySelector('#inbox-draft').value===body&&document.querySelector('#inbox-draft-status').textContent.includes('Saved'),result.body);
  assert.equal(f.store.inbox.read(slot.token,sourceId,session.sessionBinding).draft.body,result.body);
  assert.equal(f.store.inbox.sends(slot.token,sourceId,session.sessionBinding).sends.length,0);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const label=provider==='sms'?'SMS':'WhatsApp';
  assert.equal(await page.getByRole('button',{name:`Disconnect ${label}`,exact:true}).count(),0);
  await page.locator('#inbox-back').click();
  await page.locator('#inbox-connections > summary').click();
  await page.getByRole('button',{name:`Disconnect ${label}`,exact:true}).click();
  await page.getByText('Disconnected here. Saved messages remain.',{exact:true}).waitFor();
  assert.deepEqual(disconnects,[{connectionId:'twilio-test',expectedRevision:1}]);
  assert.equal(await page.getByRole('button',{name:`Disconnect ${label}`,exact:true}).count(),0);
  await page.locator('#inbox-list button').first().click();
  assert.equal(await page.getByText('Private signed message fixture',{exact:true}).isVisible(),true);
  page.on('dialog',d=>d.accept());await page.locator('#signout-button').click();
  await page.waitForFunction(()=>document.querySelector('#inbox-messaging-list').childElementCount===0&&document.querySelector('#inbox-messaging-status').textContent==='');
});
