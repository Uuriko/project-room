// Rebuild the self-contained sanitizer so offline runtime packages still boot.
// Dependency versions are pinned by package-lock.json; esbuild by cloudflare/.
// 2026-09-30 (phase-2 gap audit L-P2-21): resolve esbuild through Node's module
// resolution anchored at cloudflare/package.json instead of a hardcoded
// ../cloudflare/node_modules/esbuild path — the hardcoded path assumes npm's
// flat node_modules layout and breaks under pnpm's symlinked layout.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Deferred into main(): importing this module for findPackageDir (unit tests)
// must not require the esbuild toolchain to be installed.
const cloudflareRequire = () => createRequire(join(process.cwd(), 'cloudflare', 'package.json'));

// Walk up from a bundled input file to the owning package.json (for license
// attribution). Returns null when a relative walk leaves the tree (the old
// skip behavior). THROWS instead of hanging when an absolute path walks all
// the way to the filesystem root with no package.json: the old loop's
// `dir !== '.'` guard is never false at `/` (dirname('/') === '/'), so it
// spun forever — reachable in practice because esbuild resolves symlinks and
// pnpm's realpaths live outside the repo (the layout this script was adapted
// for on 2026-09-30).
export function findPackageDir(file) {
  let dir = dirname(file);
  while (dir !== '.') {
    let name = null;
    try { name = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).name; } catch { /* keep walking */ }
    if (name) return dir;
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`build-gmail-sanitizer: no package.json with a name found above ${file}`);
    dir = parent;
  }
  return null;
}

async function main() {
const { build } = cloudflareRequire()('esbuild');
const result = await build({ stdin: { contents: "export { default } from 'sanitize-html';", resolveDir: process.cwd(), sourcefile: 'gmail-sanitizer-entry.mjs' }, plugins: [{ name: 'builtin-esm', setup(b) { b.onResolve({ filter: /^(path|url|fs)$/ }, args => ({ path: args.path, namespace: 'builtin-esm' })); b.onLoad({ filter: /.*/, namespace: 'builtin-esm' }, args => ({ contents: `export * from 'node:${args.path}';`, loader: 'js' })); } }], bundle: true, format: 'esm', platform: 'node', target: 'node24', minify: true, legalComments: 'inline', metafile: true, outfile: 'server/vendor/gmail-html-sanitizer.mjs', banner: { js: '// Generated by scripts/build-gmail-sanitizer.mjs. See gmail-html-LICENSES.txt.' } });
const packages = new Map();
for (const file of Object.keys(result.metafile.inputs).filter(p => p.includes('node_modules/'))) {
  const dir = findPackageDir(file);
  if (dir === null || packages.has(dir)) continue;
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json')));
  const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENSE-MIT.txt'].find(name => existsSync(join(dir, name)));
  if (!license && pkg.name !== 'launder') throw new Error('Missing license for ' + pkg.name);
  packages.set(dir, `${pkg.name}@${pkg.version}\n${readFileSync(license ? join(dir, license) : 'scripts/vendor-licenses/apostrophe.txt', 'utf8')}`);
}
writeFileSync('server/vendor/gmail-html-LICENSES.txt', [...packages.values()].join('\n\n---\n\n'));
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) await main();
