import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { RoomStore } from '../server/store.mjs';
import { createRoomServer } from '../server/http.mjs';
import { initialRoom } from '../server/bootstrap.mjs';

for (const width of [1360, 390]) test(`file recovery and uncertain retry at ${width}px`, { timeout: 30000 }, async t => {
  const store = new RoomStore(':memory:'); store.initialize(initialRoom());
  const token = store.issueAccessKey('commons', 'owner');
  const server = createRoomServer({ store });
  let browser;
  t.after(async () => { await browser?.close(); server.closeStreams(); server.closeAllConnections(); await new Promise(r => server.close(r)); store.close(); });
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width, height: 900 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.locator('#access-key').fill(token);
  await page.getByRole('button', { name: 'Enter room', exact: true }).click();
  await page.locator('#main').waitFor({ state: 'visible' });
  await page.locator('#composer-options > summary').click();
  await page.locator('#remember-drafts').check();
  await page.locator('#file-picker').setInputFiles({ name: 'recover.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') });
  await page.locator('#composer-files').getByText('Ready', { exact: true }).waitFor();
  await page.reload();
  await page.locator('#composer-files').getByText('Ready', { exact: true }).waitFor();
  assert.equal(await page.locator('#message-input').inputValue(), '');
  assert.equal(store.room('commons').state.messages.length, 0);
  const attempts = [];
  await page.route('**/commands', async route => {
    attempts.push(route.request().postDataJSON());
    if (attempts.length === 1) { await route.fetch(); await route.abort(); }
    else await route.continue();
  });
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.locator('#composer-status').filter({ hasText: 'Draft kept' }).waitFor();
  assert.equal(store.room('commons').state.messages.length, 1);
  await page.route('**/attachments/*/status', route => route.fulfill({ status: 503, json: { error: { message: 'Status unavailable' } } }));
  await page.reload();
  await page.locator('#composer-files').getByText('Status unavailable', { exact: true }).waitFor();
  assert.equal(await page.locator('#message-input').evaluate(e => e.readOnly), true);
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('#composer-files .composer-file').length === 0);
  assert.equal(attempts.length, 2); assert.deepEqual(attempts[0], attempts[1]);
  assert.equal(store.room('commons').state.messages.length, 1);
  await page.unroute('**/attachments/*/status');
  await page.unroute('**/commands');
  await page.locator('#file-picker').setInputFiles({ name: 'expired.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') });
  await page.locator('#composer-files').getByText('Ready', { exact: true }).waitFor();
  await page.route('**/commands', route => route.abort());
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.locator('#composer-status').filter({ hasText: 'Draft kept' }).waitFor();
  store.db.prepare("UPDATE room_attachments SET expires_at=1 WHERE filename='expired.txt'").run();
  await page.unroute('**/commands');
  await page.reload();
  await page.locator('#composer-files').getByText('File unavailable. Remove it and choose it again.', { exact: true }).waitFor();
  assert.equal(await page.locator('#message-input').evaluate(e => e.readOnly), true);
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.getByRole('button', { name: 'Remove expired.txt', exact: true }).waitFor();
  assert.equal(await page.locator('#message-input').evaluate(e => e.readOnly), false);
  await page.getByRole('button', { name: 'Remove expired.txt', exact: true }).click();
  assert.equal(await page.locator('#composer-files .composer-file').count(), 0);
  assert.equal(store.room('commons').state.messages.length, 1, 'definitive rejection is not a message');
  await page.locator('#file-picker').setInputFiles({ name: 'checking.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') });
  await page.locator('#composer-files').getByText('Ready', { exact: true }).waitFor();
  let release;
  const held = new Promise(resolve => { release = resolve; });
  t.after(() => release());
  await page.route('**/attachments/*/status', async route => {
    const response = await route.fetch();
    await held; await route.fulfill({ response });
  });
  await page.reload();
  await page.locator('#composer-files').getByText('Checking…', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Remove checking.txt', exact: true }).click();
  assert.equal(await page.locator('#composer-files .composer-file').count(), 0);
  const finished = page.waitForResponse('**/attachments/*/status');
  release(); await finished;
  await page.unroute('**/attachments/*/status');
  await page.reload();
  await page.locator('#main').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#composer-files .composer-file').count(), 0, 'late verification never restores a removed file');
  await page.locator('#file-picker').setInputFiles({ name: 'unsent.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') });
  await page.locator('#composer-files').getByText('Ready', { exact: true }).waitFor();
  let warning = '';
  page.once('dialog', async dialog => { warning = dialog.message(); await dialog.dismiss(); });
  await page.locator('#signout-button').click();
  assert.match(warning, /clear unsent drafts/);
  assert.equal(await page.locator('#composer-files .composer-file').count(), 1, 'cancel exit retains file-only draft');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#signout-button').click();
  await page.locator('#auth-panel').waitFor({ state: 'visible' });
  assert.equal(await page.evaluate(() => sessionStorage.getItem('project-room:drafts:v4')), null);
  assert.deepEqual(errors, []);
});
