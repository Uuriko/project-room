import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, rmSync } from 'node:fs';
import { chromium } from 'playwright';
import { createAcceptanceFixture } from './acceptance-fixture.mjs';
import { createRoomServer } from '../server/http.mjs';
import { fillAccessKey } from './auth-signin.mjs';
for (const width of [390, 1440]) test(`new account setup saves answers, resumes, skips and reopens at ${width}px`, async t => {
  const f = createAcceptanceFixture(), account = f.store.accountForMember('commons', 'owner');
  f.store.db.prepare('UPDATE accounts SET onboarded=0 WHERE id=?').run(account.id);
  const key = f.store.issueAccountAccessKey(account.id), server = createRoomServer({ store: f.store });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = 'http://127.0.0.1:' + server.address().port, browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); server.closeStreams(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); f.store.close(); rmSync(f.directory, { recursive: true, force: true }); });
  const page = await browser.newPage({ viewport: { width, height: 900 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + '/?account=1'); await fillAccessKey(page, key); await page.locator('#auth-form button[type=submit]').click();
  const dialog = page.locator('#account-setup-dialog'); await dialog.waitFor({ state: 'visible' });
  await page.locator('#setup-name').fill('Morgan'); await page.locator('#setup-purpose').selectOption('team');
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
  await dialog.getByRole('heading', { name: 'Bring your messages together' }).waitFor();
  await dialog.getByLabel('Gmail', { exact: true }).check(); await dialog.getByLabel('Slack · coming later', { exact: true }).check();
  await dialog.getByText('Gmail connection is not enabled here yet.', { exact: false }).waitFor();
  assert.equal(await dialog.getByRole('button', { name: 'Connect Gmail', exact: true }).isDisabled(), true);
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
  await dialog.getByRole('heading', { name: 'You’re ready' }).waitFor();
  await page.reload(); await dialog.getByRole('heading', { name: 'You’re ready' }).waitFor();
  const saved = JSON.parse(f.store.db.prepare('SELECT data_json FROM account_setup WHERE account_id=?').get(account.id).data_json);
  assert.deepEqual(saved.platforms, ['Gmail', 'Slack']); assert.equal(saved.purpose, 'team'); assert.equal(saved.name, 'Morgan');
  await dialog.getByRole('button', { name: 'Back', exact: true }).click();
  await dialog.getByRole('heading', { name: 'Bring your messages together' }).waitFor();
  mkdirSync('test-results/gmail-setup', { recursive: true });
  await page.screenshot({ path: `test-results/gmail-setup/setup-${width}.png`, fullPage: true });
  assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await dialog.getByRole('button', { name: 'Set up later', exact: true }).click(); await dialog.waitFor({ state: 'hidden' });
  await page.reload(); await page.locator('#inbox-panel').waitFor({ state: 'visible' });
  assert.equal(await dialog.isVisible(), false);
  await page.getByText('Manage inbox', { exact: true }).click(); await page.getByRole('button', { name: 'Personalize setup' }).click();
  await dialog.getByRole('heading', { name: 'Bring your messages together' }).waitFor();
  assert.deepEqual(errors, []);
});

test('Connect Gmail returns from Google into saved setup with real imported fixture mail', async t => {
  const { gmailContractFixture } = await import('./gmail-contract-fixture.mjs');
  const f = createAcceptanceFixture(), account = f.store.accountForMember('commons', 'owner');
  f.store.db.prepare('UPDATE accounts SET onboarded=0 WHERE id=?').run(account.id);
  const key = f.store.issueAccountAccessKey(account.id), message = gmailContractFixture().messages[0].response.message;
  const config = { clientId: 'fixture.apps.googleusercontent.com', clientSecret: 'fixture-secret', tokenKey: '42'.repeat(32), redirectUri: '',
    fetchImpl: async url => {
      if (url.includes('/token')) return Response.json({ access_token: 'fixture-access', refresh_token: 'fixture-refresh', scope: 'https://www.googleapis.com/auth/gmail.modify' });
      if (url.endsWith('/profile')) return Response.json({ emailAddress: 'morgan@gmail.test' });
      if (url.includes('/messages?')) return Response.json({ messages: [{ id: message.id }] });
      return Response.json(message);
    } };
  const server = createRoomServer({ store: f.store, gmailAuth: config });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = 'http://127.0.0.1:' + server.address().port; config.redirectUri = origin + '/api/auth/gmail/callback';
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); server.closeStreams(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); f.store.close(); rmSync(f.directory, { recursive: true, force: true }); });
  const page = await browser.newPage(), errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('https://accounts.google.com/**', route => {
    const url = new URL(route.request().url()); assert.equal(url.searchParams.get('scope'), 'https://www.googleapis.com/auth/gmail.modify');
    return route.fulfill({ status: 302, headers: { Location: config.redirectUri + '?state=' + url.searchParams.get('state') + '&code=fixture-code' }, body: '' });
  });
  await page.goto(origin + '/?account=1'); await fillAccessKey(page, key); await page.locator('#auth-form button[type=submit]').click();
  const dialog = page.locator('#account-setup-dialog'); await dialog.waitFor({ state: 'visible' });
  await page.locator('#setup-name').fill('Morgan'); await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
  await dialog.getByRole('button', { name: 'Connect Gmail', exact: true }).click();
  await dialog.getByText('Connected: morgan@gmail.test', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
  await dialog.getByRole('button', { name: 'Open my inbox', exact: true }).click();
  await page.locator('#inbox-subject').getByText('A small collaboration', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Sync Gmail', exact: true }).click();
  await page.getByText('Manage inbox', { exact: true }).click();
  await page.getByRole('button', { name: 'Disconnect', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm disconnect', exact: true }).click();
  await page.getByRole('button', { name: 'Connect Gmail', exact: true }).waitFor();
  assert.equal(f.store.db.prepare('SELECT count(*) n FROM gmail_mailboxes').get().n, 0);
  assert.equal(f.store.db.prepare('SELECT count(*) n FROM private_inbox_sources').get().n, 1);
  assert.deepEqual(errors, []);
});
