// Mobile sign-in history is a real navigation boundary: Back must leave the
// email step, Forward must restore it, and pending writes must stay visible.
import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "playwright";
import { RoomStore } from "../server/store.mjs";
import { createRoomServer } from "../server/http.mjs";
import { initialRoom } from "../server/bootstrap.mjs";
import { createMagicLinkMailer } from "../server/magic-links.mjs";

test("mobile email taps and browser Back/Forward retain the room and fence a pending sign-in link", { timeout: 45000 }, async t => {
  const directory = mkdtempSync(join(tmpdir(), "room-mobile-history-"));
  const store = new RoomStore(join(directory, "room.sqlite"));
  store.initialize(initialRoom());
  const sent = [];
  const server = createRoomServer({ store, magicLinkMailer: createMagicLinkMailer({ send: async payload => sent.push(payload) }) });
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const resources = { browser: null };
  t.after(async () => {
    await resources.browser?.close();
    server.closeStreams(); server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
    store.close(); rmSync(directory, { recursive: true, force: true });
  });
  const browser = resources.browser = await chromium.launch({ headless: true, ...(process.env.ROOM_TEST_CHROMIUM_PATH ? { executablePath: process.env.ROOM_TEST_CHROMIUM_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const destination = `${origin}/?room=commons`;
  await page.goto(destination);
  await page.locator("#email-signin").waitFor({ state: "visible" });
  await page.evaluate(() => { window.historyEvents = 0; addEventListener("popstate", () => { window.historyEvents++; }); });
  await page.locator("#email-signin").tap();
  await page.locator('#email-auth-panel [name="email"]').waitFor({ state: "visible" });
  const back = await page.locator("#email-auth-back").boundingBox();
  const email = await page.locator("#email-auth-panel label").first().boundingBox();
  assert.ok(back.height >= 44, "Back has a usable touch target");
  assert.ok(back.y + back.height <= email.y, "Back does not overlap the email label or input");
  assert.equal(page.url(), destination);
  await page.evaluate(() => history.back());
  await page.waitForFunction(() => window.historyEvents >= 1 && !document.querySelector("#signin-methods").hidden);
  assert.equal(await page.locator("#email-signin").evaluate(element => element === document.activeElement), true);
  assert.equal(page.url(), destination, "browser Back stays on the intended room sign-in page");
  await page.evaluate(() => history.forward());
  await page.waitForFunction(() => window.historyEvents >= 2 && !document.querySelector("#email-auth-step").hidden);
  await page.locator("#email-auth-back").tap();
  await page.waitForFunction(() => window.historyEvents >= 3 && !document.querySelector("#signin-methods").hidden);
  await page.locator("#email-signin").tap();
  const form = page.locator('#email-auth-panel [data-signin-form="magic-request"]');
  await form.locator('[name="email"]').fill("mobile-navigation@example.invalid");
  let release;
  const held = new Promise(resolve => { release = resolve; });
  let requests = 0;
  await page.route("**/api/auth/magic/request", route => { requests++; release(route); });
  await form.locator('button[type="submit"]').tap();
  const route = await held;
  await page.evaluate(() => history.back());
  await page.waitForFunction(() => window.historyEvents >= 5 && history.state?.roomSigninStep === "email");
  assert.equal(await page.locator("#email-auth-step").isVisible(), true, "pending email request remains visible after Back is undone");
  assert.equal(page.url(), destination);
  assert.equal(requests, 1, "navigation does not replay the pending request");
  await route.continue();
  await page.locator("#email-auth-panel").getByText(/Check .* for your sign-in link/).waitFor();
  assert.equal(sent.length, 1, "one real request reaches the configured mail seam");
  await page.locator("#email-auth-back").tap();
  await page.waitForFunction(() => !document.querySelector("#signin-methods").hidden);
  assert.equal(page.url(), destination);
  await page.locator("#email-signin").tap();
  await page.reload();
  await page.locator("#email-signin").tap();
  await page.locator("#email-auth-back").tap();
  await page.locator("#email-signin").waitFor({ state: "visible" });
  assert.equal(page.url(), destination, "Back after reload leaves email in one tap");
  assert.deepEqual(errors, []);
});
