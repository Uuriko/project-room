// Frozen candidate manifest: pin runtime, assets, schema and package hashes so
// tests and deployment preparation refer to the same bytes. Deterministic: the
// same tree always produces the same manifest, so drift is a byte comparison.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { publicAssets } from "./runtime-package.mjs";

export const MANIFEST_PATH = "scripts/CANDIDATE-MANIFEST.json";
const DEPLOYMENT_FILES = [".github/workflows/deploy-prod.yml", "scripts/deploy-recovery.mjs", "cloudflare/room.mjs", "cloudflare/storage.mjs", "cloudflare/bootstrap.mjs",
  "cloudflare/build-assets.mjs", "cloudflare/wrangler.jsonc", "cloudflare/package.json", "cloudflare/pnpm-lock.yaml"];
const PACKAGE_FILES = ["package.json", "package-lock.json"];

const sha256 = buffer => "sha256:" + createHash("sha256").update(buffer).digest("hex");
const read = (root, path) => readFileSync(join(root, path));

export function pinRuntime(root) {
  const pkg = JSON.parse(read(root, "package.json").toString());
  const node = pkg.engines?.node;
  if (typeof node !== "string" || !node.trim()) throw new Error("package.json must pin engines.node");
  const workflow = read(root, ".github/workflows/test.yml").toString();
  const ci = /node-version:\s*(\d+)/.exec(workflow)?.[1];
  if (!ci || !node.includes(ci)) throw new Error("CI node version must satisfy engines.node");
  return { node, ci };
}

export function pinSchema(root) {
  const fence = read(root, "server/writer-fence.mjs").toString();
  const version = Number(/export const STORE_SCHEMA_VERSION = (\d+);/.exec(fence)?.[1]);
  if (!Number.isSafeInteger(version) || version < 0) throw new Error("STORE_SCHEMA_VERSION not found");
  return version;
}

export function pinFiles(root, paths) {
  const pins = {};
  for (const path of [...paths].sort()) pins[path] = sha256(read(root, path));
  return pins;
}

// The docs/agents/*.html pages are generated by scripts/build-agent-docs.mjs
// and are no longer committed, so pinning their bytes would pin build output.
// Pin the generator inputs instead — the rendered pages are a deterministic
// function of these files, so input drift is output drift.
const GENERATED_AGENT_PAGE = /^docs\/agents\/[^/]+\.html$/;
const agentDocInputs = publicAssets
  .filter(path => GENERATED_AGENT_PAGE.test(path))
  .map(path => path.replace(/\.html$/, ".md"));
const ASSET_FILES = [
  ...publicAssets.filter(path => !GENERATED_AGENT_PAGE.test(path)),
  ...agentDocInputs,
  "docs/agents/paste.md",
  "docs/agents/START.md",
  "scripts/build-agent-docs.mjs",
  "server/connect-snippets.mjs",
];

export function buildCandidateManifest(root) {
  return {
    contractVersion: 1,
    runtime: pinRuntime(root),
    storeSchemaVersion: pinSchema(root),
    assets: pinFiles(root, ASSET_FILES),
    deployment: pinFiles(root, DEPLOYMENT_FILES),
    packages: pinFiles(root, PACKAGE_FILES),
  };
}

const EXPECTED_KEYS = ["contractVersion", "runtime", "storeSchemaVersion", "assets", "deployment", "packages"];
export function manifestDrift(expected, actual) {
  const drift = [];
  if (!actual || typeof actual !== "object" || Array.isArray(actual)) return ["manifest is not an object"];
  if (JSON.stringify(Object.keys(actual).sort()) !== JSON.stringify([...EXPECTED_KEYS].sort())) drift.push("manifest keys differ");
  if (actual.contractVersion !== 1) drift.push("contractVersion");
  if (actual.storeSchemaVersion !== expected.storeSchemaVersion) drift.push("storeSchemaVersion");
  if (JSON.stringify(actual.runtime) !== JSON.stringify(expected.runtime)) drift.push("runtime");
  for (const section of ["assets", "deployment", "packages"]) {
    const a = expected[section] ?? {}, b = actual[section] ?? {};
    for (const key of new Set([...Object.keys(a), ...Object.keys(b)]))
      if (a[key] !== b[key]) drift.push(`${section}:${key}`);
  }
  return drift;
}

// Human-readable drift report for failure output: the REAL expected-vs-actual
// values behind every manifestDrift() entry, plus the one-command cure.
// manifestDrift() stays the terse machine list (tests pin its strings); this
// is what a reader of a failing check gets, so the cure needs no source dive.
const MAX_DRIFT_LINES = 25;
export function formatManifestDrift(expected, actual) {
  const drift = manifestDrift(expected, actual);
  if (!drift.length) return "";
  const lines = drift.slice(0, MAX_DRIFT_LINES).map(entry => {
    if (entry === "manifest is not an object") return "manifest: the committed file is not a JSON object";
    if (entry === "manifest keys differ")
      return `keys: tree [${EXPECTED_KEYS.join(", ")}], committed [${actual && typeof actual === "object" ? Object.keys(actual).sort().join(", ") : "?"}]`;
    if (entry === "contractVersion") return `contractVersion: committed ${actual?.contractVersion}, tree ${expected.contractVersion}`;
    if (entry === "storeSchemaVersion") return `storeSchemaVersion: committed ${actual?.storeSchemaVersion}, tree ${expected.storeSchemaVersion}`;
    if (entry === "runtime") return `runtime: committed ${JSON.stringify(actual?.runtime)}, tree ${JSON.stringify(expected.runtime)}`;
    const cut = entry.indexOf(":");
    const section = entry.slice(0, cut), key = entry.slice(cut + 1);
    const tree = expected[section]?.[key], committed = actual?.[section]?.[key];
    const state = committed === undefined ? "missing from the committed manifest" : tree === undefined ? "stale pin (file no longer in the tree set)" : "hash differs";
    return `${entry}: ${state}\n  committed: ${committed ?? "(absent)"}\n  tree:      ${tree ?? "(absent)"}`;
  });
  if (drift.length > MAX_DRIFT_LINES) lines.push(`… and ${drift.length - MAX_DRIFT_LINES} more drifted entries`);
  lines.push("Cure (one command, then re-run this check):",
    "  node scripts/candidate-manifest.mjs --write",
    "Then review `git diff scripts/CANDIDATE-MANIFEST.json` — every changed pin should trace to a file this change touched.");
  return lines.join("\n");
}

const isMain = process.argv[1] && import.meta.url === new URL(process.argv[1], "file:").href;
if (isMain) {
  const root = process.cwd(), manifest = buildCandidateManifest(root);
  if (process.argv.includes("--write")) {
    const { writeFileSync } = await import("node:fs");
    writeFileSync(join(root, MANIFEST_PATH), JSON.stringify(manifest, null, 2) + "\n");
    console.log(`froze ${MANIFEST_PATH}: schema ${manifest.storeSchemaVersion}, ${Object.keys(manifest.assets).length} assets, ${Object.keys(manifest.deployment).length} deployment files`);
  } else console.log(JSON.stringify(manifest, null, 2));
}
