import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, rmSync } from 'node:fs';
import { chromium } from 'playwright';
import { createAcceptanceFixture } from './acceptance-fixture.mjs';
import { createRoomServer } from '../server/http.mjs';

for (const [name, viewport] of [['desktop', { width: 1300, height: 950 }], ['mobile', { width: 390, height: 844 }]]) test(`human automation ${name}: create, consent, exact retry, pause and scope edit`, async t => {
  const f = createAcceptanceFixture(), server = createRoomServer({ store: f.store, streamInterval: 30 });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ headless: true }), origin = `http://127.0.0.1:${server.address().port}`, errors = [];
  t.after(async () => { await browser.close(); server.closeStreams(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); f.store.close(); rmSync(f.directory, { recursive: true, force: true }); });
  async function open(key) {
    const context = await browser.newContext({ viewport, reducedMotion: 'reduce' }), page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(8000);
    await page.goto(origin); await page.locator('#access-key').fill(key); await page.getByRole('button', { name: 'Enter room', exact: true }).click();
    await page.locator('#main').waitFor(); await page.locator('#room-about > summary').click();
    await page.locator('#automations-open').click(); return page;
  }
  const page = await open(f.keys.owner);
  await page.getByRole('button', { name: 'New automation', exact: true }).click();
  await page.locator('#automation-title').fill('Daily <check>');
  await page.locator('#automation-recipient').selectOption('guest');
  await page.locator('#automation-prompt').fill('Summarize the next step.');
  await page.locator('#automation-form button[type="submit"]').click();
  await page.locator('#automation-detail').getByRole('button', { name: 'Enable', exact: true }).click();
  const peer = await open(f.keys.guest);
  await peer.locator('#automation-list').getByRole('button', { name: 'Daily <check>', exact: true }).click();
  await peer.locator('#automation-detail').getByRole('button', { name: 'Accept', exact: true }).click();
  const requests = [];
  await page.route('**/api/rooms/commons/commands', async route => {
    const command = route.request().postDataJSON();
    if (command.type !== 'message.posted' || !command.data.automationId) return route.continue();
    requests.push(command); const response = await route.fetch();
    if (requests.length === 1) await route.abort('failed'); else await route.fulfill({ response });
  });
  await page.locator('#automation-detail').getByRole('button', { name: 'Run', exact: true }).click();
  await page.locator('#automation-retry').click();
  await page.locator('#automation-status').filter({ hasText: 'Request posted' }).waitFor();
  assert.equal(requests.length, 2); assert.deepEqual(requests[0], requests[1]);
  const automationId = requests[0].data.automationId;
  assert.equal(f.store.room('commons').state.automations[automationId].dispatchCount, 1);
  assert.equal(await page.locator('#automation-detail').getByRole('button', { name: 'Edit', exact: true }).count(), 0);
  await page.locator('#automation-detail').getByRole('button', { name: 'Pause', exact: true }).click();
  await page.locator('#automation-detail').getByText('Paused · 9 runs left', { exact: true }).waitFor();
  const requestId = requests[0].data.messageId;
  assert.equal(f.store.room('commons').state.replyRequests[requestId].status, 'open');
  f.store.command(f.keys.owner, 'commons', { id: 'cancel', type: 'reply_request.cancelled', data: { requestMessageId: requestId, expectedRequestRevision: 0, reason: 'Done testing' } });
  await page.locator('#automation-detail').getByRole('button', { name: 'Edit', exact: true }).click();
  await page.locator('#automation-prompt').fill('Refined prompt'); await page.locator('#automation-form button[type="submit"]').click();
  await page.locator('#automation-detail').getByText('Refined prompt', { exact: true }).waitFor();
  assert.equal(f.store.room('commons').state.automations[automationId].recipientAccepted, false);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  mkdirSync('test-results', { recursive: true }); await page.locator('#automations-dialog').screenshot({ path: `test-results/automation-${name}.png` });
  await page.locator('#automations-close').click();
  assert.equal(await page.evaluate(() => document.activeElement.id), 'automations-open');
  await page.locator('#automations-open').click();
  await page.getByRole('button', { name: 'New automation', exact: true }).click();
  await page.locator('#automation-title').fill('Private unsent state');
  await page.locator('#automation-recipient').selectOption('guest');
  await page.locator('#automation-prompt').fill('Do not retain across accounts');
  await page.route('**/api/rooms/commons/commands', async route => {
    if (route.request().postDataJSON().type === 'automation.created') return route.abort('failed');
    return route.fallback();
  });
  await page.locator('#automation-form button[type="submit"]').click();
  await page.locator('#automation-retry').waitFor();
  f.store.revoke(f.keys.owner);
  await page.locator('#access-key').waitFor();
  assert.equal(await page.locator('#automations-dialog').evaluate(el => el.open), false);
  assert.equal(await page.locator('#automation-prompt').inputValue(), '');
  await page.locator('#access-key').fill(f.keys.guest);
  await page.getByRole('button', { name: 'Enter room', exact: true }).click();
  await page.locator('#main').waitFor();
  if (!await page.locator('#automations-open').isVisible()) await page.locator('#room-about > summary').click();
  await page.locator('#automations-open').click();
  assert.equal(await page.locator('#automation-retry').isVisible(), false);
  assert.equal(await page.locator('#automation-form').isVisible(), false);
  assert.equal(await page.locator('#automation-status').textContent(), '');
  assert.deepEqual(errors, []);
});
