import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { rmSync,readFileSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { createAcceptanceFixture } from './acceptance-fixture.mjs';
import { createRoomServer } from '../server/http.mjs';
import { TelegramConnectionRegistry } from '../server/telegram-connection-registry.mjs';
import { TelegramReceiveQueue } from '../server/telegram-receive-queue.mjs';
import { createTelegramConnections } from '../server/telegram-connections.mjs';

for(const mobile of [false,true])test(`full-stack Telegram Inbox acceptance (${mobile?'mobile':'desktop'})`,async t=>{
  const f=createAcceptanceFixture(),registryPath=join(f.directory,'registry.sqlite'),queuePath=join(f.directory,'queue.sqlite');
  let rdb=new DatabaseSync(registryPath),qdb=new DatabaseSync(queuePath);
  const b={accountId:f.store.accountForMember('commons','owner').id,connectionId:'telegram-one',authEpoch:0};
  const token='123456:abcdefghijklmnopqrstuvwxyz',key=Buffer.alloc(32,9),offsets=[];
  let registry=new TelegramConnectionRegistry({db:rdb,key}),queue=new TelegramReceiveQueue({db:qdb,key,...b});
  registry.configure({...b,expectedRevision:0,botId:'123456',token,chatIds:[44]});
  const service=()=>createTelegramConnections({store:f.store,registry,connections:[{...b,queue}],fetchImpl:async(url,options)=>{
    assert.equal(url,`https://api.telegram.org/bot${token}/getUpdates`);
    const offset=JSON.parse(options.body).offset;offsets.push(offset);
    return Response.json({ok:true,result:offset===0?[{update_id:9,message:{message_id:1,chat:{id:44},from:{id:44},date:1700000000,text:'Acceptance: shared context stays private until I choose otherwise.'}}]:[]});
  }});
  let connections=service();
  const proxy={list:s=>connections.list(s),sync:(...args)=>connections.sync(...args),disconnect:(...args)=>connections.disconnect(...args)};
  const server=createRoomServer({store:f.store,telegramConnections:proxy});await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch({headless:true});
  t.after(async()=>{await browser.close();server.closeStreams();server.closeAllConnections();await new Promise(r=>server.close(r));rdb.close();qdb.close();f.store.close();rmSync(f.directory,{recursive:true,force:true});});
  const page=await browser.newPage({viewport:mobile?{width:390,height:844}:{width:1280,height:900}});page.setDefaultTimeout(8000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));const before=f.store.room('commons').sequence;
  await page.goto(`http://127.0.0.1:${server.address().port}/?room=commons`);await page.locator('#sign-in-entry').click();
  await page.locator('#access-key').fill(f.store.issueAccountAccessKey(b.accountId));await page.locator('#auth-form button[type=submit]').click();
  await page.locator('#main').waitFor({state:'visible'});await page.locator('#nav-inbox').click();await page.locator('#inbox-connections > summary').click();
  await page.getByRole('button',{name:'Sync Telegram',exact:true}).click();
  await page.getByText('1 message synced.',{exact:true}).waitFor({state:'attached'});
  await page.locator('#inbox-source-body').getByText('Acceptance: shared context stays private until I choose otherwise.',{exact:true}).waitFor();
  assert.equal(await page.locator('#inbox-ask').isVisible(),false);
  assert.equal(f.store.room('commons').sequence,before);assert.equal(f.store.inbox.verify().versions,1);
  // Reopen persistent receiver storage; next browser sync must use saved offset.
  rdb.close();qdb.close();
  assert.equal(readFileSync(registryPath).includes(Buffer.from(token)),false);
  assert.equal(readFileSync(queuePath).includes(Buffer.from('Acceptance: shared context')),false);
  rdb=new DatabaseSync(registryPath);qdb=new DatabaseSync(queuePath);
  registry=new TelegramConnectionRegistry({db:rdb,key});queue=new TelegramReceiveQueue({db:qdb,key,...b});connections=service();
  if(mobile)await page.locator('#inbox-back').click();
  await page.getByRole('button',{name:'Sync Telegram',exact:true}).click();
  await page.getByText('0 messages synced.',{exact:true}).waitFor({state:'attached'});
  assert.deepEqual(offsets,[0,10]);assert.equal(f.store.inbox.verify().versions,1);
  if(mobile&&await page.locator('#inbox-back').isVisible())await page.locator('#inbox-back').click();
  await page.getByRole('button',{name:'Disconnect Telegram',exact:true}).click();
  await page.getByText('Disconnected here. Saved messages remain.',{exact:true}).waitFor();
  assert.equal(registry.status(b).state,'disconnected');assert.equal(f.store.inbox.verify().versions,1);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));assert.deepEqual(errors,[]);
});
