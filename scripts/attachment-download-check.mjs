import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { RoomStore } from '../server/store.mjs';
import { createRoomServer } from '../server/http.mjs';
import { initialRoom } from '../server/bootstrap.mjs';

for (const mobile of [false, true]) test(`verified file download ${mobile ? 'mobile' : 'desktop'}`, async t => {
  const store = new RoomStore(':memory:'); store.initialize(initialRoom());
  const token = store.issueAccessKey('commons', 'owner');
  const bytes = new Uint8Array([0, 255, 7]);
  store.attachments.stage(token, 'commons', { id: 'download-file', filename: 'résumé.html', mediaType: 'text/html', bytes });
  store.command(token, 'commons', { id: 'post-file', type: 'message.posted', data: { messageId: 'file-message', body: 'Shared file', attachmentIds: ['download-file'] } });
  const server = createRoomServer({ store });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); server.closeAllConnections(); server.closeStreams(); await new Promise(resolve => server.close(resolve)); store.close(); });
  const context = await browser.newContext({ acceptDownloads: true, viewport: mobile ? { width: 390, height: 844 } : { width: 1360, height: 900 }, isMobile: mobile, hasTouch: mobile });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.locator('#access-key').fill(token);
  await page.getByRole('button', { name: 'Enter room', exact: true }).click();
  const button = page.getByRole('button', { name: 'Download résumé.html', exact: true });
  await button.waitFor();
  const screenshots = await mkdtemp(join(tmpdir(), 'room-file-ui-'));
  const screenshot = join(screenshots, mobile ? 'mobile.png' : 'desktop.png');
  await page.screenshot({ path: screenshot });
  console.log('UI screenshot: ' + screenshot);
  const bounds = await button.boundingBox();
  assert.ok(bounds.height >= 44);
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= (mobile ? 390 : 1360));
  const received = page.waitForEvent('download');
  await button.click();
  const download = await received;
  assert.equal(download.suggestedFilename(), 'résumé.html');
  assert.deepEqual(new Uint8Array(await readFile(await download.path())), bytes);
  await button.waitFor();
  let unblock;
  let unexpectedDownload = false;
  page.on('download', () => { unexpectedDownload = true; });
  await page.route('**/attachments/download-file', async route => {
    await new Promise(resolve => { unblock = resolve; });
    try { await route.continue(); } catch {}
  });
  const requested = page.waitForRequest('**/attachments/download-file');
  await button.click(); await requested;
  await page.getByRole('button', { name: 'Cancel download of résumé.html' }).click();
  unblock();
  await button.waitFor();
  assert.equal(unexpectedDownload, false);
  await page.unroute('**/attachments/download-file');
  await page.locator('#file-picker').setInputFiles({ name: 'from-composer.txt', mimeType: 'text/plain', buffer: Buffer.from(bytes) });
  await page.locator('#composer-files').getByText('Ready', { exact: true }).waitFor();
  assert.equal(store.room('commons').state.messages.length, 1, 'staging is not sending');
  let loseMessageResponse = true;
  const attempts = [];
  await page.route('**/commands', async route => {
    const command = route.request().postDataJSON();
    if (command.type === 'message.posted') {
      attempts.push(command);
      if (loseMessageResponse) { loseMessageResponse = false; await route.fetch(); await route.abort(); return; }
    }
    await route.continue();
  });
  await page.locator('#message-input').fill('Uploaded from the composer');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.locator('#composer-status').filter({ hasText: 'Draft kept' }).waitFor();
  assert.equal(await page.locator('#message-input').evaluate(element => element.readOnly), true);
  assert.equal(await page.locator('#attach-file').isDisabled(), true);
  assert.equal(store.room('commons').state.messages.length, 2, 'message committed even though confirmation was lost');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.getByRole('button', { name: 'Download from-composer.txt', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('#message-input').value === '');
  assert.equal(attempts.length, 2);
  assert.deepEqual(attempts[1], attempts[0], 'retry preserves the exact event and file IDs');
  await page.unroute('**/commands');
  assert.equal(store.room('commons').state.messages.length, 2);
  assert.equal(await page.locator('#composer-files .composer-file').count(), 0);
  const posted = store.room('commons').state.messages.at(-1);
  assert.equal(posted.attachments[0].filename, 'from-composer.txt');
  assert.deepEqual(store.attachments.readCommitted(token, 'commons', posted.attachments[0].id).bytes, bytes);
  let loseUploadResponse = true;
  await page.route('**/attachments/*', async route => {
    if (route.request().method() === 'PUT' && loseUploadResponse) {
      loseUploadResponse = false; await route.fetch(); await route.abort();
    } else await route.continue();
  });
  await page.locator('#file-picker').setInputFiles({ name: 'retry.txt', mimeType: 'text/plain', buffer: Buffer.from(bytes) });
  await page.locator('#composer-files').getByRole('button', { name: 'Retry', exact: true }).click();
  await page.locator('#composer-files').getByText('Ready', { exact: true }).waitFor();
  assert.equal(store.db.prepare("SELECT count(*) n FROM room_attachments WHERE filename='retry.txt'").get().n, 1);
  const removed = page.waitForResponse(response => response.request().method() === 'DELETE' && response.url().includes('/attachments/'));
  await page.locator('#composer-files').getByRole('button', { name: 'Remove', exact: true }).click();
  assert.equal((await removed).status(), 200);
  assert.equal(store.db.prepare("SELECT bytes FROM room_attachments WHERE filename='retry.txt'").get().bytes, null);
  await page.locator('#file-picker').setInputFiles({ name: 'captionless.txt', mimeType: 'text/plain', buffer: Buffer.from(bytes) });
  await page.locator('#composer-files').getByText('Ready', { exact: true }).waitFor();
  assert.equal(await page.locator('#message-input').inputValue(), '');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.getByRole('button', { name: 'Download captionless.txt', exact: true }).waitFor();
  assert.equal(store.room('commons').state.messages.at(-1).body, '');
  assert.equal(store.room('commons').state.messages.length, 3);
  await page.locator('#message-search').fill('captionless.txt');
  await page.locator('#search-list').getByText('captionless.txt', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
});
