import test from 'node:test';
import assert from 'node:assert/strict';
import { RoomStore } from '../server/store.mjs';
import { initialRoom } from '../server/bootstrap.mjs';
import { createRoomServer } from '../server/http.mjs';
import { operatorWakeIndex } from '../server/operator-wake-index.mjs';
import { linkWithProof } from './helpers/link-with-proof.mjs';
test('selected poll echoes newest only after authorization; heartbeat capability and default order remain independent',async t=>{
 const s=new RoomStore(':memory:');s.initialize(initialRoom());
 const owner=s.issueAccessKey('commons','owner'),identity=s.identities.create('Synthetic newest HTTP');
 linkWithProof(s,owner,'commons',identity,{memberId:'worker',permissions:[]});
 const other=s.identities.create('Unrelated HTTP');
 const server=createRoomServer({store:s});await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(async()=>{server.closeStreams();server.closeAllConnections();await new Promise(r=>server.close(r));s.close();});
 const origin=`http://127.0.0.1:${server.address().port}`;
 const call=async(path,body,who=identity)=>{const r=await fetch(origin+path,{method:body?'POST':'GET',headers:{authorization:'Bearer '+who.secret,...(body?{'content-type':'application/json'}:{})},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,value:await r.json()};};
 const hb={hostId:'host',mode:'pull-only',listenerLease:{roomId:'commons'}};
 assert.equal((await call('/api/agent-heartbeats',hb)).value.wakeSelection,undefined);
 assert.equal((await call('/api/agent-wakes/poll?roomId=commons&order=newest&hostId=host&waitMs=0')).status,503);
 const reason='Synthetic route',plan=operatorWakeIndex(s,{reason});operatorWakeIndex(s,{reason,planHash:plan.planHash,requestId:'route-install'},true);
 assert.deepEqual((await call('/api/agent-heartbeats',hb)).value.wakeSelection,{version:1,newest:true,roomId:'commons'});
 s.transaction(()=>{const insert=s.db.prepare("INSERT INTO agent_wake_signals VALUES(?,?,'mention','commons',?,?,NULL)");for(let n=0;n<60;n++)insert.run('signal-'+n.toString().padStart(3,'0'),identity.identityId,'message-'+n,n);});
 const path='/api/agent-wakes/poll?roomId=commons&hostId=host&waitMs=0';
 const newest=await call(path+'&order=newest');assert.equal(newest.status,200);assert.equal(newest.value.order,'newest');assert.equal(newest.value.roomId,'commons');assert.equal(newest.value.pendingWakes[0].signalId,'signal-059');assert.equal(newest.value.more,true);
 const oldest=await call(path);assert.equal(oldest.status,200);assert.equal(Object.hasOwn(oldest.value,'order'),false);assert.equal(oldest.value.pendingWakes[0].signalId,'signal-000');
 assert.equal((await call(path+'&cursor='+encodeURIComponent(newest.value.nextCursor))).status,422);
 for(const query of ['&order=other','&order=newest&order=newest'])assert.equal((await call(path+query)).status,422);
 assert.equal((await call('/api/agent-wakes/poll?order=newest&hostId=host&waitMs=0')).status,422);
 assert.equal((await call(path+'&order=newest',null,other)).status,403);
 assert.equal(s.db.prepare('SELECT count(*) n FROM agent_wake_signals WHERE delivered_at IS NOT NULL').get().n,0);
});
