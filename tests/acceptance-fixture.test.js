import test from "node:test";
import assert from "node:assert/strict";
import { copyFileSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createAcceptanceFixture } from "../scripts/acceptance-fixture.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

test("acceptance setup is isolated, repeatable, scoped and includes invitation states", () => {
  const a = createAcceptanceFixture(), b = createAcceptanceFixture();
  try {
    assert.notEqual(a.directory, b.directory);
    assert.notEqual(a.keys.owner, b.keys.owner);
    const state = a.store.snapshot(a.keys.owner, "commons").state;
    assert.match(state.room.title, /Disposable Test/);
    assert.deepEqual(state.members.producer.permissions, ["accept_work", "complete_work"]);
    assert.deepEqual(state.members.reviewer.permissions, ["verify"]);
    assert.deepEqual(state.members.guest.permissions, []);
    assert.equal(state.workItems["test-handoff"].sourceMessageId, "test-request");
    assert.equal(a.store.shareLinks.preview(a.links.valid).link.remainingJoins, 10);
    for (const label of ["expired", "cancelled", "full"]) assert.throws(() => a.store.shareLinks.preview(a.links[label]), { code: "link_unavailable" });
    assert.equal(a.store.verifyInvitationAudit().consistent, true);
  } finally {
    for (const f of [a, b]) { f.store.close(); rmSync(f.directory, { recursive: true, force: true }); }
  }
});

// The loader's generated module is a cache, not a source of truth: a copy
// truncated by a failed write (0 bytes — the EPERM write-fault specimen that
// once failed 41 suites as "createAcceptanceFixture is not a function") must
// be regenerated byte-perfect on the next import, never trusted on existence.
test("fixture loader regenerates a truncated generated module byte-perfect", async () => {
  // One level under the repo root so the generated module's ../server and
  // ../src imports resolve exactly as they do from scripts/.
  const dir = mkdtempSync(join(ROOT, ".fixture-loader-test-"));
  try {
    for (const name of ["acceptance-fixture.mjs", ".acceptance-fixture.b64", ".acceptance-fixture.b64.fix"]) {
      copyFileSync(join(ROOT, "scripts", name), join(dir, name));
    }
    const loaderUrl = pathToFileURL(join(dir, "acceptance-fixture.mjs")).href;
    const first = await import(loaderUrl);
    assert.equal(typeof first.createAcceptanceFixture, "function");
    const generated = readdirSync(dir).find(name => name.endsWith(".generated.mjs"));
    assert.ok(generated, "loader must generate its module on first import");
    const pristine = readFileSync(join(dir, generated));
    assert.ok(pristine.length > 0);
    writeFileSync(join(dir, generated), "");
    const second = await import(`${loaderUrl}?regenerate=1`);
    assert.equal(typeof second.createAcceptanceFixture, "function");
    assert.deepEqual(readFileSync(join(dir, generated)), pristine, "truncated cache must be restored byte-perfect");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
