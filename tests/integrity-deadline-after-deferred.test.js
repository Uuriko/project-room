import test from 'node:test';
import assert from 'node:assert/strict';
import { RoomStore } from '../server/store.mjs';
import { initialRoom } from '../server/bootstrap.mjs';

test('expired starvation-first batch preserves progress and failures without starting incremental work', async t => {
  const store = new RoomStore(':memory:');
  t.after(() => store.close());
  store.initialize(initialRoom('deadline-proof'));
  await store.verifyRoomIntegrity();
  store.noteDeferredOutcome(false);
  store.noteDeferredOutcome(false);
  store.recordIntegrityFailure('synthetic_probe', '', new Error('synthetic failure'));
  const snapshot = store.readIntegritySnapshot();
  const cursor = () => store.db.prepare('SELECT step FROM integrity_job_cursor WHERE singleton=1').get().step;
  const before = cursor();
  const original = store.incrementalIntegrityCheck.bind(store);
  let incrementalCalls = 0;
  store.incrementalIntegrityCheck = () => { incrementalCalls++; return original(); };
  const realNow = Date.now;
  let now = realNow();
  Date.now = () => now;
  t.after(() => { Date.now = realNow; });
  const result = await store.verifyRoomIntegrity({ deadline: now + 5000, yieldBetween: async () => { now += 10000; } });
  assert.equal(incrementalCalls, 0);
  assert.equal(result.budgetExceeded, 1);
  assert.equal(result.deferredSkips, 0);
  assert.equal(result.verified, 0);
  assert.equal(result.checked, 0);
  assert.equal(result.swept, 0);
  assert.equal(result.verifiedRooms, store.integrityVerifiedRooms());
  assert.ok(result.failures.some(row => row.step === 'synthetic_probe'));
  assert.equal(store.readIntegritySnapshot(), snapshot);
  assert.equal(cursor(), before + 1);
  const next = await store.verifyRoomIntegrity({ deadline: now + 5000 });
  assert.equal(incrementalCalls, 1);
  assert.equal(next.deferred.ran, 2);
  assert.equal(cursor(), before + 3);
  assert.ok(next.failures.some(row => row.step === 'synthetic_probe'));
});
